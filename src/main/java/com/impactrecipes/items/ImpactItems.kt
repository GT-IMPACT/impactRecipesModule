    public override fun get(amount: Int): ItemStack? {
        if (coreItem != null) {
            return coreItem.get(amount)?.copy()
        }
        if (machineItem != null) {
            return machineItem.get(amount.toLong())?.copy()
        }
        if (blockItem != null) {
            return ItemStack(
                blockItem,
                amount,
                meta,
            )
        }
        if (nativeItem != null) {
            val stack = ItemStack(
                nativeItem,
                amount,
                meta,
            )
            if (nativeItem is DrillHeads) {
                return DrillHeads.create(stack)
            }
            return stack
        }
        val name = registryName ?: return null
        return RecipeItems.item(
            mod = modId,
            name = name,
            meta = meta,
            count = amount,
        )
    }
